-- ============================================================================
-- 10. IMMUTABILITY TRIGGER FOR STOCK LEDGER
-- ============================================================================

create or replace function public.prevent_inventory_stock_movement_mutation()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  raise exception 'Inventory stock movements are immutable';
end;
$$;

drop trigger if exists trg_inventory_stock_movement_immutable
on public.inventory_stock_movements;

create trigger trg_inventory_stock_movement_immutable
before update or delete
on public.inventory_stock_movements
for each row
execute function public.prevent_inventory_stock_movement_mutation();


